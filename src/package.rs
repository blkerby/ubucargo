/// Filesystem target selected for a package operation.
#[derive(Debug, Eq, PartialEq)]
enum Target {
    /// An existing Ubucargo source package.
    Existing(PathBuf),
    /// A clean destination that does not yet exist.
    New {
        /// Directory that will contain the source package and orig tarball.
        parent: PathBuf,
        /// Explicit source directory, or none when the Debian source name is used.
        requested: Option<PathBuf>,
    },
}

/// Debcargo configuration values that affect package identity.
struct PackageConfig {
    /// Complete in-tree configuration text.
    contents: String,
    /// Whether the Debian source name includes the crate's semver line.
    semver_suffix: bool,
    /// Effective repack suffix, including debcargo's default for exclusions.
    repack_suffix: Option<String>,
}

